"""Regenerates Source/ShootingArena/Private/Analyzer/ArenaMatchLogSchema.inc from the committed
template database (Content/Data/ShootingArenaLog.db). Run from the repository root."""
import re, sqlite3, sys

src = sys.argv[1] if len(sys.argv) > 1 else 'Content/Data/ShootingArenaLog.db'
dst = sys.argv[2] if len(sys.argv) > 2 else 'Source/ShootingArena/Private/Analyzer/ArenaMatchLogSchema.inc'
con = sqlite3.connect(src)
con.text_factory = bytes
order = {'table': 0, 'trigger': 1, 'index': 2, 'view': 3}
rows = []
for typ, name, sql in con.execute("select type,name,sql from sqlite_master where sql is not null"):
    typ = typ.decode()
    try:
        text = sql.decode('utf-8')
    except UnicodeDecodeError:
        text = sql.decode('cp949', 'replace')
    text = re.sub(r'--[^\n]*', '', text)
    text = re.sub(r'[ \t]+\n', '\n', text).strip()
    rows.append((order[typ], name.decode(), text))
rows.sort(key=lambda r: r[0])
# tables are created before everything else; views last
out = ['// Generated by Tools/ArenaMatchLog/GenerateSchema.py from Content/Data/ShootingArenaLog.db. Do not edit.',
       'static const TCHAR* const GArenaMatchLogSchema[] =', '{']
for _, name, text in rows:
    assert ')RAWSQL"' not in text
    out.append('\tTEXT(R"RAWSQL(' + text + ')RAWSQL"),')
out.append('};')
with open(dst, 'w', encoding='utf-8-sig', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print(len(rows), 'statements ->', dst)
